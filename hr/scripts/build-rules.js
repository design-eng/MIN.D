function table(head, rows, widths) {
  const total = widths.reduce((a, b) => a + b, 0);
  // 긴 문장은 가운데 정렬하면 읽기 어려우므로 왼쪽으로 흘린다
  const cell = (text, w, opt = {}) => new TableCell({
    width: { size: w, type: WidthType.DXA },
    shading: opt.head ? { type: ShadingType.CLEAR, fill: SURF, color: 'auto' } : undefined,
    margins: { top: 90, bottom: 90, left: 130, right: 130 },
    children: [new Paragraph({
      alignment: (opt.center && String(text).length <= 20) ? AlignmentType.CENTER : AlignmentType.LEFT,
      spacing: { line: 264 },
      children: [T(text, { bold: !!opt.head, size: 19 })],
    })],
  });
  return new Table({
    width: { size: total, type: WidthType.DXA },
    columnWidths: widths,
    borders: {
      top:    { style: BorderStyle.SINGLE, size: 8, color: INK },
      bottom: { style: BorderStyle.SINGLE, size: 8, color: INK },
      left:   { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' },
      right:  { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' },
      insideHorizontal: { style: BorderStyle.SINGLE, size: 4, color: LINE },
      insideVertical:   { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' },
    },
    rows: [
      new TableRow({ tableHeader: true,
        children: head.map((h, i) => cell(h, widths[i], { head: true, center: i > 0 })) }),
      ...rows.map(r => new TableRow({
        children: r.map((c, i) => cell(c, widths[i], { center: i > 0 })) })),
    ],
  });
}

