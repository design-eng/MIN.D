function build(st) {
  const C = [];
  C.push(p("컨셉트와 프로세스 · 대학원 박사과정 · 2026-2학기", { size: 16, color: GRAY, after: 60 }));
  C.push(p("제2차 과제 피드백", { size: 34, bold: true, after: 80 }));
  C.push(p(st.topic, { size: 20, color: GRAY, after: 100, border: ruleThick }));

  C.push(h("1. 제출한 것"));
  st.did.forEach(t => C.push(p(t, { numbering: { reference: "b", level: 0 }, after: 74 })));

  C.push(h("2. 빠진 것"));
  st.missing.forEach(([k, v], i) => {
    C.push(rich([{ t: String(i + 1) + "  ", bold: true, color: GRAY }, { t: k, bold: true }], { after: 40 }));
    C.push(p(v, { color: GRAY, after: 104 }));
  });

  C.push(h("3. 다음 회차까지 할 것"));
  st.next.forEach(([k, v], i) => {
    C.push(rich([{ t: k, bold: true }], { numbering: { reference: "q", level: 0 }, after: 40 }));
    C.push(p(v, { color: GRAY, after: 104 }));
  });

  C.push(h("4. 다섯 분 모두에게"));
  COMMON.forEach(([k, v]) => {
    C.push(rich([{ t: k, bold: true }], { numbering: { reference: "b", level: 0 }, after: 40 }));
    C.push(p(v, { color: GRAY, after: 88 }));
  });

  return new Document({
    creator: "MIN.D", title: "제2차 과제 피드백",
    numbering: { config: [
      { reference: "q", levels: [{ level: 0, format: LevelFormat.DECIMAL, text: "%1.", alignment: AlignmentType.START,
        style: { paragraph: { indent: { left: convertInchesToTwip(0.35), hanging: convertInchesToTwip(0.25) } } } }] },
      { reference: "b", levels: [{ level: 0, format: LevelFormat.BULLET, text: "—", alignment: AlignmentType.START,
        style: { paragraph: { indent: { left: convertInchesToTwip(0.35), hanging: convertInchesToTwip(0.25) } } } }] },
    ]},
    styles: { default: { document: { run: { font: F, size: 20, color: INK } } } },
    sections: [{ properties: { page: { margin: { top: 1080, right: 1100, bottom: 1000, left: 1100 } } }, children: C }],
  });
}

(async () => {
  const outDir = process.argv[2];
  for (const st of STUDENTS) {
    const buf = await Packer.toBuffer(build(st));
    fs.writeFileSync(outDir + "/" + st.file, buf);
    console.log("생성:", st.file);
  }
})();
